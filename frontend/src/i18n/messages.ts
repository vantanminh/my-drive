// UI string dictionaries for the dashboard. `en` is the source of truth;
// `vi` must translate every key (enforced by the Record<keyof typeof en> type
// and tests/i18n.test.mjs).

export type Lang = 'en' | 'vi';
export const LANG_KEY = 'my-drive.lang';

export function currentLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'vi') return saved;
  } catch {
    // Storage may be unavailable (private mode); fall through to navigator.
  }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('vi') ? 'vi' : 'en';
}

